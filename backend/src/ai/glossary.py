# 한자 연속 토큰 (한 단위)
_HANJA_RE = re.compile(r"[一-鿿]+")
# 이미 '한글(한자)' 병기된 부분 보호용
_ALREADY_ANNOTATED_RE = re.compile(r"[가-힣]+\([一-鿿]+\)")


def _convert_token(token: str) -> str:
    """단일 한자 토큰을 '한글(한자)' 형식으로 변환."""
    if token in TERMS_MAP:
        return f"{TERMS_MAP[token]}({token})"
    parts: list[str] = []
    converted_any = False
    for ch in token:
        kor = CHAR_MAP.get(ch)
        if kor:
            parts.append(kor)
            converted_any = True
        else:
            parts.append(ch)  # 모르는 한자는 그대로
    if not converted_any:
        return token
    return f"{''.join(parts)}({token})"


def annotate_hanja(text: str) -> str:
    """텍스트의 모든 한자 토큰을 '한글(한자)' 형식으로 자동 병기.

    이미 '한글(한자)' 패턴은 보존(중복 방지). 한자가 없으면 텍스트 그대로.
    """
    if not text:
        return text
    placeholders: list[str] = []

    def _stash(m: re.Match[str]) -> str:
        placeholders.append(m.group(0))
        return f"\x00{len(placeholders) - 1}\x00"

    protected = _ALREADY_ANNOTATED_RE.sub(_stash, text)
    converted = _HANJA_RE.sub(lambda m: _convert_token(m.group(0)), protected)

    def _unstash(m: re.Match[str]) -> str:
        return placeholders[int(m.group(1))]

    return re.sub(r"\x00(\d+)\x00", _unstash, converted)
