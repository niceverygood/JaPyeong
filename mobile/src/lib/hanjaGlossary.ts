/**
 * 한글+한자 쌍에 대한 의미 설명을 찾는다.
 * 1) 단어 매핑이 있으면 그것
 * 2) 글자별 매핑을 ' · '로 잇기
 * 3) 둘 다 없으면 한글 자체를 반환
 */
export function lookupMeaning(korean: string, hanja: string): string {
  const term = TERM_MEANINGS[hanja];
  if (term) return term;
  const chars = [...hanja]
    .map((c) => CHAR_MEANINGS[c])
    .filter((s): s is string => Boolean(s));
  if (chars.length > 0) return chars.join(" · ");
  return korean;
}
